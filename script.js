let currentLang = localStorage.getItem('csparepart-language') || 'ar';
const validCategories = ['all', 'axles', 'brakes', 'towing', 'electrical'];
const requestedCategory = new URLSearchParams(window.location.search).get('category');
let selectedCategory = validCategories.includes(requestedCategory) ? requestedCategory : 'all';
let searchQuery = '';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('csparepart-language', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  const langToggleBtns = document.querySelectorAll('.lang-toggle');
  langToggleBtns.forEach((btn) => {
    btn.textContent = lang === 'ar' ? 'English' : 'العربية';
  });

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[lang] && copy[lang][key]) {
      node.innerHTML = copy[lang][key];
    }
  });

  // تحديث روابط وتفاصيل الواتساب في قسم نبقيك على الطريق بناءً على الكود المحدث
  const contactLabelElement = document.querySelector('.contact-section p');
  if (contactLabelElement) {
    contactLabelElement.innerHTML = lang === 'ar' 
      ? `<a href="https://api.whatsapp.com/send?phone=+968 9983 8481&text=السلام%20عليكم،%20أريد%20طلب%20قطعة%20غيار%20للمقطورة" target="_blank" style="color: #38bdf8; text-decoration: none;"></a>`
      : `<a href="https://api.whatsapp.com/send?phone=+968 9983 8481&text=Hello,%20I%20want%20to%20order%20a%20trailer%20spare%20part" target="_blank" style="color: #38bdf8; text-decoration: none;"></a>`;
  }

  // تحديث زر الواتساب العائم أيضاً
  const whatsappFloat = document.querySelector('.whatsapp-float');
  if (whatsappFloat) {
    whatsappFloat.href = "https://api.whatsapp.com/send?phone=+968 9983 8481&text=السلام%20عليكم،%20أريد%20طلب%20قطعة%20غيار%20للمقطورة";
  }

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (copy[lang] && copy[lang][key]) {
      node.placeholder = copy[lang][key];
    }
  });

  renderProducts();
}

function renderProducts() {
  const gridContainer = document.querySelector('#product-grid');
  if (!gridContainer) return;

  const filtered = productsList.filter((item) => {
    const matchCategory = selectedCategory === 'all' || item.category === selectedCategory;
    const matchSearch = `${item.id} ${item.name.en} ${item.name.ar}`.toLowerCase().includes(searchQuery.toLowerCase());
    return matchCategory && matchSearch;
  });

  const countDisplay = document.querySelector('#product-count');
  if (countDisplay) {
    countDisplay.textContent = `${filtered.length} ${copy[currentLang].results}`;
  }

  if (filtered.length === 0) {
    gridContainer.innerHTML = `<p class="empty-products" style="grid-column: 1/-1; text-align: center; color: #94a3b8; padding: 40px;">${copy[currentLang].noResults}</p>`;
    if (window.AOS) AOS.refreshHard();
    return;
  }

  gridContainer.innerHTML = filtered.map((item) => `
    <article class="product-card" data-aos="fade-up" data-aos-duration="800">
      <div class="product-image-placeholder" style="width: 100%; height: 160px; background: #0f172a; display: flex; align-items: center; justify-content: center; border-radius: 6px; margin-bottom: 12px; overflow: hidden;">
        <img src="${item.image}" alt="${item.name[currentLang]}" style="max-width: 80%; max-height: 80%; object-fit: contain;" />
      </div>
      <h3>${item.name[currentLang]}</h3>
      <p style="color: #94a3b8; font-size: 0.85rem;">OEM / ${item.id}</p>
      <div class="product-bottom" style="display: flex; align-items: center; justify-content: space-between; margin-top: 15px; border-top: 1px solid #334155; padding-top: 10px;">
        <p style="margin: 0; font-size: 0.85rem; color: #94a3b8;"><b style="color: #38bdf8;"></b></p>
        <button class="order-button" type="button" style="background: #0284c7; color: #fff; border: none; padding: 6px 12px; border-radius: 4px; cursor: pointer;">${copy[currentLang].order}</button>
      </div>
    </article>
  `).join('');

  if (window.AOS) AOS.refreshHard();
}

document.addEventListener('DOMContentLoaded', () => {
  if (window.AOS) {
    AOS.init({ duration: 800, once: true });
  }

  applyLanguage(currentLang);

  document.addEventListener('click', (e) => {
    if (e.target.matches('.lang-toggle')) {
      applyLanguage(currentLang === 'en' ? 'ar' : 'en');
    }
  });

  const filterBtns = document.querySelectorAll('.filter-group button');
  filterBtns.forEach((btn) => {
    if (btn.dataset.filter === selectedCategory) btn.classList.add('selected');
    btn.addEventListener('click', (e) => {
      filterBtns.forEach((b) => b.classList.remove('selected'));
      e.target.classList.add('selected');
      selectedCategory = e.target.dataset.filter;
      renderProducts();
    });
  });

  // توجيه زر الطلب إلى قسم نموذج التواصل وتعبة اسم القطعة
  document.addEventListener('click', (e) => {
    const orderButton = e.target.closest('.order-button');
    if (!orderButton) return;

    const productName = orderButton.closest('.product-card')?.querySelector('h3')?.textContent.trim();
    if (productName) {
      const contactForm = document.querySelector('#contact-form');
      const requestField = contactForm?.querySelector('[name="message"]') || contactForm?.querySelector('#message');
      
      if (contactForm && requestField) {
        requestField.value = `طلب قطعة: ${productName}`;
        contactForm.scrollIntoView({ behavior: 'smooth', block: 'start' });
        requestField.focus();
      } else {
        window.location.href = `index.html?product=${encodeURIComponent(productName)}#contact`;
      }
    }
  });

  const searchInput = document.querySelector('#catalog-search');
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      searchQuery = e.target.value;
      renderProducts();
    });
  }

  // إرسال البيانات فورياً إلى SheetDB
  const contactForm = document.querySelector('#contact-form');
  if (contactForm) {
    const requestedProduct = new URLSearchParams(window.location.search).get('product');
    const requestField = contactForm.querySelector('[name="message"]') || contactForm.querySelector('#message');
    if (requestedProduct && requestField) {
      requestField.value = `طلب قطعة: ${requestedProduct}`;
      requestField.focus({ preventScroll: true });
      requestAnimationFrame(() => {
        contactForm.scrollIntoView({ behavior: 'smooth', block: 'start' });
      });
    }

    contactForm.addEventListener('submit', async (e) => {
      e.preventDefault();
      const status = contactForm.querySelector('.form-status') || document.createElement('p');
      if (!contactForm.querySelector('.form-status')) {
        status.className = 'form-status';
        contactForm.appendChild(status);
      }

      const nameVal = contactForm.querySelector('[name="name"]')?.value || contactForm.querySelector('#name')?.value || '-';
      const phoneVal = contactForm.querySelector('[name="email"]')?.value || contactForm.querySelector('[name="phone"]')?.value || contactForm.querySelector('#phone')?.value || '-';
      const messageVal = contactForm.querySelector('[name="message"]')?.value || contactForm.querySelector('#message')?.value || '-';
      const currentDate = new Date().toLocaleString('ar-EG');

      status.textContent = currentLang === 'ar' ? 'جاري إرسال طلبك...' : 'Sending your request...';

      // البيانات المرسلة لمطابقة أعمدة شيت جوجل تماماً
      const orderPayload = {
        data: [
          {
            "الاسم": nameVal,
            "الهاتف": phoneVal,
            "الطلب": messageVal,
            "التاريخ": currentDate
          }
        ]
      };

      try {
        const response = await fetch(SHEET_API_URL, {
          method: 'POST',
          headers: {
            'Accept': 'application/json',
            'Content-Type': 'application/json'
          },
          body: JSON.stringify(orderPayload)
        });

        if (response.ok) {
          status.textContent = currentLang === 'ar' ? 'تم إرسال طلبك وتسجيله بنجاح!' : 'Your request has been submitted successfully!';
          contactForm.reset();
        } else {
          status.textContent = currentLang === 'ar' ? 'حدث خطأ أثناء حفظ الطلب، حاول ثانية.' : 'An error occurred while saving the request.';
        }
      } catch (error) {
        console.error("SheetDB Error:", error);
        status.textContent = currentLang === 'ar' ? 'حدث خطأ في الاتصال بالسيرفر.' : 'Connection error.';
      }
    });
  }
});
