let currentLang = localStorage.getItem('csparepart-language') || 'en';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('csparepart-language', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  const langToggleBtn = document.querySelector('.lang-toggle');
  if (langToggleBtn) {
    langToggleBtn.textContent = lang === 'ar' ? 'English' : 'العربية';
  }
  
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[lang] && copy[lang][key]) {
      node.innerHTML = copy[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (copy[lang] && copy[lang][key]) {
      node.placeholder = copy[lang][key];
    }
  });

  renderProducts();
}

const langToggleBtn = document.querySelector('.lang-toggle');
if (langToggleBtn) {
  langToggleBtn.addEventListener('click', () => {
    applyLanguage(currentLang === 'en' ? 'ar' : 'en');
  });
}


let selectedCategory = 'all';
let searchQuery = '';

function renderProducts() {
  const gridContainer = document.querySelector('#product-grid');
  if (!gridContainer) return;

  const filtered = productsList.filter((item) => {
    const matchCategory = selectedCategory === 'all' || item.category === selectedCategory;
    const matchSearch = `${item.id} ${item.name.en} ${item.name.ar}`.toLowerCase().includes(searchQuery.toLowerCase());
    return matchCategory && matchSearch;
  });

  const countDisplay = document.querySelector('#product-count');
  if (countDisplay) {
    countDisplay.textContent = `${filtered.length} ${copy[currentLang].results}`;
  }

  if (filtered.length === 0) {
    gridContainer.innerHTML = `<p class="empty-products">${copy[currentLang].noResults}</p>`;
    return;
  }

  gridContainer.innerHTML = filtered.map((item) => `
    <article class="product-card">
      <h3>${item.name[currentLang]}</h3>
      <p>OEM / ${item.id}</p>
      <div class="product-bottom">
        <p>${copy[currentLang].priceFrom} <b>${item.price} OMR</b></p>
        <button class="order-button" type="button">${copy[currentLang].order}</button>
      </div>
    </article>
  `).join('');
}

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);
  renderProducts();

  const filterBtns = document.querySelectorAll('.filter-group button');
  filterBtns.forEach((btn) => {
    btn.addEventListener('click', (e) => {
      filterBtns.forEach((b) => b.classList.remove('selected'));
      e.target.classList.add('selected');
      selectedCategory = e.target.dataset.filter;
      renderProducts();
    });
  });

  const searchInput = document.querySelector('#catalog-search');
  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      searchQuery = e.target.value;
      renderProducts();
    });
  }

  const contactForm = document.querySelector('#contact-form');
  if (contactForm) {
    contactForm.addEventListener('submit', async (e) => {
      e.preventDefault();
      const status = contactForm.querySelector('.form-status');
      const formData = new FormData(contactForm);
      
      status.textContent = currentLang === 'ar' ? 'جاري إرسال طلبك...' : 'Sending your request...';

      try {
        const response = await fetch(contactForm.action, {
          method: 'POST',
          body: formData,
          headers: { 'Accept': 'application/json' }
        });

        if (response.ok) {
          status.textContent = currentLang === 'ar' ? 'تم إرسال طلبك بنجاح! سنتواصل معك قريباً.' : 'Your request has been sent successfully! We will contact you soon.';
          contactForm.reset();
        } else {
          status.textContent = currentLang === 'ar' ? 'حدث خطأ، يرجى المحاولة مرة أخرى.' : 'An error occurred, please try again.';
        }
      } catch (error) {
        status.textContent = currentLang === 'ar' ? 'حدث خطأ في الاتصال.' : 'Connection error.';
      }
    });
  }
});